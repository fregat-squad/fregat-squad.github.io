function makeDossier({ id, number, name, posterName, age, stamp, reward, traits, aliases, advice, articles }) {
  const chief = id === "boss";
  const portrait = id === "echo" ? "dossiers/rasul/kitchen.png" : "dossiers/portraits/" + id + ".png";
  return {
    id, name, posterName, age, stamp, reward, portrait, chief,
    role: chief ? "DJ FREGAT" : "Участник сквада",
    code: "FS—" + String(number).padStart(3, "0"),
    notes: [
      { title: "Особые приметы", lines: [traits] },
      { title: "Возможные клички", lines: [aliases] },
      { title: "Рекомендации по общению", lines: [advice] },
      { title: "Статьи внутреннего кодекса", lines: articles.map((line, i) => "§ " + (i + 1) + ". " + line) }
    ],
    photos: [{ src: portrait, caption: name }]
  };
}

